/**
 * Deletes ONE record — an entity, relationship, or hypothesis — from a research domain's
 * dataset, via a NEW, auto-numbered migration file, same "every mutation is a migration"
 * convention as `applyResearchUpdate.ts`/`createResearchDomain.ts`/`manageTrackedTickers.ts`. See
 * `src/store/sqlGen.ts`'s `renderDeleteSql` for why this is a real `DELETE` (not a
 * retraction/soft-delete) and why only these three collections are deletable at all.
 *
 * Usage:
 *   yarn workspace @quant-fusion/research-store run delete:research-item -- \
 *     --domain fusion --collection entities --id entity-x
 *
 * Refuses (no file written) if the id doesn't exist in that collection, or if deleting it would
 * leave a dangling reference elsewhere in the dataset (e.g. a relationship still pointing at a
 * deleted entity) — see `renderDeleteSql`'s own doc comment.
 *
 * The generated migration file still needs ONE manual step — see `applyResearchUpdate.ts`'s own
 * doc comment for why this stays manual.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { nextMigrationNumber, renderMigrationFileSource } from '@quant-fusion/sqlite-migrations';
import { createResearchStore } from '../src/store/db.js';
import { getResearchDataset, listResearchDatasets } from '../src/store/read.js';
import {
  DELETABLE_COLLECTION_KEYS,
  renderDeleteSql,
  type DeletableCollectionKey,
} from '../src/store/sqlGen.js';
import type { ResearchStore } from '../src/index.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DEFAULT_MIGRATIONS_DIR = resolve(__dirname, '../src/migrations');

export interface DeleteResearchItemOptions {
  store?: ResearchStore;
  domain: string;
  collection: DeletableCollectionKey;
  id: string;
  migrationsDir?: string;
  now?: string;
}

export type DeleteResearchItemResult =
  | {
      ok: true;
      domain: string;
      collection: DeletableCollectionKey;
      id: string;
      migrationId: string;
      migrationPath: string;
      migrationFileName: string;
      exportName: string;
      newVersion: string;
    }
  | { ok: false; reason: string };

function idSlug(id: string): string {
  return id
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/** The full load -> delete -> validate -> generate pipeline, factored out from `main()` with
 * options so it's testable against a temp store/migrations directory rather than the real ones. */
export function deleteResearchItemMigration(
  options: DeleteResearchItemOptions,
): DeleteResearchItemResult {
  const migrationsDir = options.migrationsDir ?? DEFAULT_MIGRATIONS_DIR;
  const now = options.now ?? new Date().toISOString();
  const store = options.store ?? createResearchStore(':memory:');

  const domainRow = listResearchDatasets(store).find((d) => d.domain === options.domain);
  if (domainRow === undefined) {
    return { ok: false, reason: `no registered research domain "${options.domain}"` };
  }

  const currentResult = getResearchDataset(store, domainRow.datasetId);
  if (!currentResult.ok) {
    return { ok: false, reason: currentResult.reason };
  }

  const rendered = renderDeleteSql(currentResult.value, options.collection, options.id, now);
  if (!rendered.ok) {
    return { ok: false, reason: rendered.reason };
  }

  const nextNumber = nextMigrationNumber(migrationsDir);
  const slug = idSlug(options.id);
  const migrationId = `research-store/${nextNumber}_delete_${options.collection}_${slug}`;
  const exportName = `migration${nextNumber}Delete${options.collection.charAt(0).toUpperCase()}${options.collection.slice(1)}${slug
    .split('-')
    .filter((part) => part.length > 0)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')}`;
  const migrationFileName = `${nextNumber}_delete_${options.collection}_${slug}.ts`;
  const migrationPath = join(migrationsDir, migrationFileName);

  const source = renderMigrationFileSource({
    exportName,
    id: migrationId,
    sql: rendered.value.sql,
    docComment:
      `/** Deletes "${options.id}" from ${options.collection} in the "${options.domain}" domain ` +
      `(version -> "${rendered.value.newVersion}"), generated by\n * ` +
      `\`research-store/scripts/deleteResearchItem.ts\` — never hand-edit this file; a\n * ` +
      `correction is always a NEW migration. */`,
  });
  writeFileSync(migrationPath, source, 'utf8');

  return {
    ok: true,
    domain: options.domain,
    collection: options.collection,
    id: options.id,
    migrationId,
    migrationPath,
    migrationFileName,
    exportName,
    newVersion: rendered.value.newVersion,
  };
}

function parseArgs(argv: string[]): Record<string, string> {
  const args: Record<string, string> = {};
  for (let i = 0; i < argv.length; i++) {
    const token = argv[i];
    if (token?.startsWith('--') !== true) continue;
    const name = token.slice(2);
    const value = argv[i + 1];
    if (value === undefined) throw new Error(`--${name} needs a value`);
    args[name] = value;
    i++;
  }
  return args;
}

function isDeletableCollection(value: string): value is DeletableCollectionKey {
  return (DELETABLE_COLLECTION_KEYS as readonly string[]).includes(value);
}

function main(): void {
  const args = parseArgs(process.argv.slice(2));
  const usage =
    'Usage: delete:research-item -- --domain <domain> --collection entities|relationships|hypotheses --id <id>';
  if (args.domain === undefined || args.collection === undefined || args.id === undefined) {
    console.error(usage);
    process.exitCode = 1;
    return;
  }
  if (!isDeletableCollection(args.collection)) {
    console.error(
      `--collection must be one of ${DELETABLE_COLLECTION_KEYS.join(', ')}, got "${args.collection}"`,
    );
    process.exitCode = 1;
    return;
  }

  const result = deleteResearchItemMigration({
    domain: args.domain,
    collection: args.collection,
    id: args.id,
  });
  if (!result.ok) {
    console.error(`Refused: ${result.reason}`);
    process.exitCode = 1;
    return;
  }

  console.log(`Deleted "${result.id}" from ${result.collection} in domain "${result.domain}".`);
  console.log(`\nWrote ${result.migrationPath}.`);
  console.log('\nOne manual step left — add these two lines to src/migrations/index.ts:');
  console.log(
    `  import { ${result.exportName} } from './${result.migrationFileName.replace(/\.ts$/, '.js')}';`,
  );
  console.log(`  // ...and add ${result.exportName} to the researchStoreMigrations array.`);
}

const isMainModule =
  process.argv[1] !== undefined && import.meta.url === `file://${process.argv[1]}`;
if (isMainModule) {
  main();
}
