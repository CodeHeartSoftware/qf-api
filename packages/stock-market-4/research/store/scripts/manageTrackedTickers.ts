/**
 * Adds or removes ONE ticker from a research domain's news watchlist (`tracked_tickers` — see
 * `src/migrations/0009_tracked_tickers_table.ts`'s own doc comment) — a NEW, auto-numbered
 * migration file per change, same "every mutation is a migration" convention as
 * `applyResearchUpdate.ts`/`createResearchDomain.ts`.
 *
 * Usage:
 *   yarn workspace @quant-fusion/research-store run manage:tracked-ticker -- \
 *     --action add --domain fusion --ticker NVDA --company-name "NVIDIA"
 *   yarn workspace @quant-fusion/research-store run manage:tracked-ticker -- \
 *     --action remove --domain fusion --ticker NVDA
 *
 * The generated migration file still needs ONE manual step — see `applyResearchUpdate.ts`'s own
 * doc comment for why this stays manual.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { nextMigrationNumber, renderMigrationFileSource } from '@quant-fusion/sqlite-migrations';
import { createResearchStore } from '../src/store/db.js';
import { listResearchDatasets } from '../src/store/read.js';
import {
  renderAddTrackedTickerSql,
  renderRemoveTrackedTickerSql,
} from '../src/store/trackedTickers.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DEFAULT_MIGRATIONS_DIR = resolve(__dirname, '../src/migrations');

export interface ManageTrackedTickerOptions {
  action: 'add' | 'remove';
  domain: string;
  ticker: string;
  /** Required for `action: 'add'`; ignored for `'remove'`. */
  companyName?: string;
  migrationsDir?: string;
  now?: string;
}

export type ManageTrackedTickerResult =
  | {
      ok: true;
      domain: string;
      ticker: string;
      migrationId: string;
      migrationPath: string;
      migrationFileName: string;
      exportName: string;
    }
  | { ok: false; reason: string };

function toPascalCase(text: string): string {
  return text
    .split(/[^a-zA-Z0-9]+/)
    .filter((part) => part.length > 0)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join('');
}

export function manageTrackedTickerMigration(
  options: ManageTrackedTickerOptions,
): ManageTrackedTickerResult {
  const migrationsDir = options.migrationsDir ?? DEFAULT_MIGRATIONS_DIR;
  const now = options.now ?? new Date().toISOString();

  const store = createResearchStore(':memory:');
  const domainRow = listResearchDatasets(store).find((d) => d.domain === options.domain);
  if (domainRow === undefined) {
    return { ok: false, reason: `no registered research domain "${options.domain}"` };
  }

  const rendered =
    options.action === 'add'
      ? renderAddTrackedTickerSql(
          store,
          domainRow.datasetId,
          options.ticker,
          options.companyName ?? '',
          now,
        )
      : renderRemoveTrackedTickerSql(store, domainRow.datasetId, options.ticker);
  if (!rendered.ok) {
    return { ok: false, reason: rendered.reason };
  }

  const nextNumber = nextMigrationNumber(migrationsDir);
  const tickerSlug = options.ticker
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-');
  const migrationId = `research-store/${nextNumber}_tracked_ticker_${options.action}_${tickerSlug}`;
  const exportName = `migration${nextNumber}TrackedTicker${options.action === 'add' ? 'Add' : 'Remove'}${toPascalCase(options.ticker)}`;
  const migrationFileName = `${nextNumber}_tracked_ticker_${options.action}_${tickerSlug}.ts`;
  const migrationPath = join(migrationsDir, migrationFileName);

  const source = renderMigrationFileSource({
    exportName,
    id: migrationId,
    sql: rendered.value,
    docComment:
      options.action === 'add'
        ? `/** Adds "${options.ticker}" to the "${options.domain}" domain's news watchlist, generated by\n * \`research-store/scripts/manageTrackedTickers.ts\` — never hand-edit this file; a correction\n * is always a NEW migration. */`
        : `/** Removes "${options.ticker}" from the "${options.domain}" domain's news watchlist, generated by\n * \`research-store/scripts/manageTrackedTickers.ts\` — never hand-edit this file. */`,
  });
  writeFileSync(migrationPath, source, 'utf8');

  return {
    ok: true,
    domain: options.domain,
    ticker: options.ticker,
    migrationId,
    migrationPath,
    migrationFileName,
    exportName,
  };
}

function parseArgs(argv: string[]): Record<string, string> {
  const args: Record<string, string> = {};
  for (let i = 0; i < argv.length; i++) {
    const token = argv[i];
    if (token?.startsWith('--') !== true) continue;
    const name = token.slice(2);
    const value = argv[i + 1];
    if (value === undefined) throw new Error(`--${name} needs a value`);
    args[name] = value;
    i++;
  }
  return args;
}

function main(): void {
  const args = parseArgs(process.argv.slice(2));
  if (args.action !== 'add' && args.action !== 'remove') {
    console.error(
      'Usage: manage:tracked-ticker -- --action add|remove --domain <domain> --ticker <ticker> [--company-name <name>]',
    );
    process.exitCode = 1;
    return;
  }
  if (args.domain === undefined || args.ticker === undefined) {
    console.error(
      'Usage: manage:tracked-ticker -- --action add|remove --domain <domain> --ticker <ticker> [--company-name <name>]',
    );
    process.exitCode = 1;
    return;
  }
  if (args.action === 'add' && args['company-name'] === undefined) {
    console.error('--company-name is required for --action add');
    process.exitCode = 1;
    return;
  }

  const result = manageTrackedTickerMigration({
    action: args.action,
    domain: args.domain,
    ticker: args.ticker,
    ...(args['company-name'] !== undefined ? { companyName: args['company-name'] } : {}),
  });
  if (!result.ok) {
    console.error(`Refused: ${result.reason}`);
    process.exitCode = 1;
    return;
  }

  console.log(
    `${args.action === 'add' ? 'Added' : 'Removed'} ticker "${result.ticker}" for domain "${result.domain}".`,
  );
  console.log(`\nWrote ${result.migrationPath}.`);
  console.log('\nOne manual step left — add these two lines to src/migrations/index.ts:');
  console.log(
    `  import { ${result.exportName} } from './${result.migrationFileName.replace(/\.ts$/, '.js')}';`,
  );
  console.log(`  // ...and add ${result.exportName} to the researchStoreMigrations array.`);
}

const isMainModule =
  process.argv[1] !== undefined && import.meta.url === `file://${process.argv[1]}`;
if (isMainModule) {
  main();
}
