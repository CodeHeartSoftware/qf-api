/**
 * Adds, renames, or removes ONE entry from a research domain's registered event-type taxonomy
 * (`event_types` — see `src/migrations/0034_event_types_table.ts`'s own doc comment) — a NEW,
 * auto-numbered migration file per change, same "every mutation is a migration" convention as
 * `manageTrackedTickers.ts`. Never touches any event already recorded with the old type string —
 * see that same migration's doc comment for why.
 *
 * Usage:
 *   yarn workspace @quant-fusion/research-store run manage:event-type -- \
 *     --action add --domain fusion --type SUPPLIER_QUALIFIED
 *   yarn workspace @quant-fusion/research-store run manage:event-type -- \
 *     --action rename --domain fusion --type SUPPLIER_QUALIFIED --new-type SUPPLIER_APPROVED
 *   yarn workspace @quant-fusion/research-store run manage:event-type -- \
 *     --action delete --domain fusion --type SUPPLIER_QUALIFIED
 *
 * The generated migration file still needs ONE manual step — see `applyResearchUpdate.ts`'s own
 * doc comment for why this stays manual.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { nextMigrationNumber, renderMigrationFileSource } from '@quant-fusion/sqlite-migrations';
import { createResearchStore } from '../src/store/db.js';
import {
  renderAddEventTypeSql,
  renderDeleteEventTypeSql,
  renderRenameEventTypeSql,
} from '../src/store/eventTypes.js';
import { listResearchDatasets } from '../src/store/read.js';
import type { Result } from '../src/result.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DEFAULT_MIGRATIONS_DIR = resolve(__dirname, '../src/migrations');

export interface ManageEventTypeOptions {
  action: 'add' | 'rename' | 'delete';
  domain: string;
  type: string;
  /** Required for `action: 'rename'`; ignored otherwise. */
  newType?: string;
  migrationsDir?: string;
  now?: string;
}

export type ManageEventTypeResult =
  | {
      ok: true;
      domain: string;
      type: string;
      migrationId: string;
      migrationPath: string;
      migrationFileName: string;
      exportName: string;
    }
  | { ok: false; reason: string };

function toPascalCase(text: string): string {
  return text
    .split(/[^a-zA-Z0-9]+/)
    .filter((part) => part.length > 0)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join('');
}

export function manageEventTypeMigration(options: ManageEventTypeOptions): ManageEventTypeResult {
  const migrationsDir = options.migrationsDir ?? DEFAULT_MIGRATIONS_DIR;
  const now = options.now ?? new Date().toISOString();

  const store = createResearchStore(':memory:');
  const domainRow = listResearchDatasets(store).find((d) => d.domain === options.domain);
  if (domainRow === undefined) {
    return { ok: false, reason: `no registered research domain "${options.domain}"` };
  }

  let rendered: Result<string>;
  if (options.action === 'add') {
    rendered = renderAddEventTypeSql(store, domainRow.datasetId, options.type, now);
  } else if (options.action === 'rename') {
    if (options.newType === undefined) {
      return { ok: false, reason: '--new-type is required for --action rename' };
    }
    rendered = renderRenameEventTypeSql(store, domainRow.datasetId, options.type, options.newType);
  } else {
    rendered = renderDeleteEventTypeSql(store, domainRow.datasetId, options.type);
  }
  if (!rendered.ok) {
    return { ok: false, reason: rendered.reason };
  }

  const nextNumber = nextMigrationNumber(migrationsDir);
  const typeSlug = options.type
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-');
  const migrationId = `research-store/${nextNumber}_event_type_${options.action}_${typeSlug}`;
  const exportName = `migration${nextNumber}EventType${toPascalCase(options.action)}${toPascalCase(options.type)}`;
  const migrationFileName = `${nextNumber}_event_type_${options.action}_${typeSlug}.ts`;
  const migrationPath = join(migrationsDir, migrationFileName);

  const docComment =
    options.action === 'add'
      ? `/** Registers "${options.type}" as an event type for the "${options.domain}" domain, generated by\n * \`research-store/scripts/manageEventTypes.ts\` — never hand-edit this file; a correction\n * is always a NEW migration. */`
      : options.action === 'rename'
        ? `/** Renames the "${options.domain}" domain's registered event type "${options.type}" to\n * "${options.newType ?? ''}", generated by \`research-store/scripts/manageEventTypes.ts\` — never\n * hand-edit this file. Existing events already recorded with the old type string are untouched\n * — see \`0034_event_types_table.ts\`'s own doc comment for why. */`
        : `/** Removes the registered event type "${options.type}" from the "${options.domain}" domain, generated\n * by \`research-store/scripts/manageEventTypes.ts\` — never hand-edit this file. Existing events\n * already recorded with this type string are untouched — see \`0034_event_types_table.ts\`'s own\n * doc comment for why. */`;

  const source = renderMigrationFileSource({
    exportName,
    id: migrationId,
    sql: rendered.value,
    docComment,
  });
  writeFileSync(migrationPath, source, 'utf8');

  return {
    ok: true,
    domain: options.domain,
    type: options.type,
    migrationId,
    migrationPath,
    migrationFileName,
    exportName,
  };
}

function parseArgs(argv: string[]): Record<string, string> {
  const args: Record<string, string> = {};
  for (let i = 0; i < argv.length; i++) {
    const token = argv[i];
    if (token?.startsWith('--') !== true) continue;
    const name = token.slice(2);
    const value = argv[i + 1];
    if (value === undefined) throw new Error(`--${name} needs a value`);
    args[name] = value;
    i++;
  }
  return args;
}

function isAction(value: string): value is ManageEventTypeOptions['action'] {
  return value === 'add' || value === 'rename' || value === 'delete';
}

function main(): void {
  const args = parseArgs(process.argv.slice(2));
  const usage =
    'Usage: manage:event-type -- --action add|rename|delete --domain <domain> --type <type> [--new-type <type>]';
  if (args.action === undefined || !isAction(args.action)) {
    console.error(usage);
    process.exitCode = 1;
    return;
  }
  if (args.domain === undefined || args.type === undefined) {
    console.error(usage);
    process.exitCode = 1;
    return;
  }
  if (args.action === 'rename' && args['new-type'] === undefined) {
    console.error('--new-type is required for --action rename');
    process.exitCode = 1;
    return;
  }

  const result = manageEventTypeMigration({
    action: args.action,
    domain: args.domain,
    type: args.type,
    ...(args['new-type'] !== undefined ? { newType: args['new-type'] } : {}),
  });
  if (!result.ok) {
    console.error(`Refused: ${result.reason}`);
    process.exitCode = 1;
    return;
  }

  const verb = { add: 'Added', rename: 'Renamed', delete: 'Removed' }[args.action];
  console.log(`${verb} event type "${result.type}" for domain "${result.domain}".`);
  console.log(`\nWrote ${result.migrationPath}.`);
  console.log('\nOne manual step left — add these two lines to src/migrations/index.ts:');
  console.log(
    `  import { ${result.exportName} } from './${result.migrationFileName.replace(/\.ts$/, '.js')}';`,
  );
  console.log(`  // ...and add ${result.exportName} to the researchStoreMigrations array.`);
}

const isMainModule =
  process.argv[1] !== undefined && import.meta.url === `file://${process.argv[1]}`;
if (isMainModule) {
  main();
}
